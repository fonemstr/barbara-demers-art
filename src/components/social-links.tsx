// Platforms without a mark above render as a text link with a proper name.
const TEXT_LABELS: Record<string, string> = {
  gmb: "Google Business",
  reddit: "Reddit",
  telegram: "Telegram",
  snapchat: "Snapchat",
};

export function SocialLinks({ profiles }: { profiles: SocialProfile[] }) {
  if (!profiles.length) return null;

  return (
    <ul className="flex flex-wrap items-center gap-4" aria-label="Social media">
      {profiles.map((profile) => {
        const icon = ICONS[profile.platform];
        const label = icon?.label ?? TEXT_LABELS[profile.platform] ?? profile.platform;
        return (
          <li key={profile.platform}>
            <a
              href={profile.url}
              target="_blank"
              rel="noopener noreferrer me"
              aria-label={`${label}: ${profile.displayName}`}
              title={label}
              className="inline-flex items-center gap-1.5 text-on-surface-muted hover:text-on-surface transition-colors text-sm"
            >
              {icon ? (
                <svg
                  viewBox="0 0 24 24"
                  width={20}
                  height={20}
                  fill="currentColor"
                  aria-hidden="true"
                >
                  <path d={icon.path} />
                </svg>
              ) : (
                <span className="capitalize">{label}</span>
              )}
            </a>
          </li>
        );
      })}
    </ul>
  );
}
